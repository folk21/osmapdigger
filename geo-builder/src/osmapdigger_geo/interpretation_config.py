"""Pure TOML resolution for bounded, dataset-selected interpretation catalogs.

This module produces the version-1 metadata subtree but does not publish packages.
Runtime ranking continues to use the ordinary resolved preference defaults.
"""

from __future__ import annotations

import math
import re
import tomllib
from pathlib import Path

from .models import MetricDefinition, MetricPreferenceDefault


_ID = re.compile(r"^[a-z][a-z0-9]*(?:[._-][a-z0-9]+)*$")
_METRIC_ID = re.compile(r"^[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+$")
_TEMPLATE_KEY = re.compile(r"^interpretation\.[a-z0-9_-]+(?:\.[a-z0-9_-]+)*$")
_MAX_CONFIG_BYTES = 256 * 1024
_RULE_TYPES = {
    "dimension-strength": (1, "minimumScore"),
    "dimension-tradeoff": (1, "maximumScore"),
    "dimension-contrast": (2, "minimumScore", "maximumScore"),
}


def _table(value: object, context: str, *, required: set[str], optional: frozenset[str] = frozenset()) -> dict:
    if not isinstance(value, dict):
        raise ValueError(f"{context} must be a table")
    missing, extra = required - value.keys(), value.keys() - required - optional
    if missing or extra:
        raise ValueError(f"{context} has missing fields {sorted(missing)} or unknown fields {sorted(extra)}")
    return value


def _identifier(value: object, context: str, pattern: re.Pattern = _ID, maximum: int = 64) -> str:
    if type(value) is not str or not 1 <= len(value) <= maximum or not pattern.fullmatch(value):
        raise ValueError(f"{context} must be a valid stable identifier")
    return value


def _integer(value: object, context: str, minimum: int, maximum: int) -> int:
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{context} must be an integer in {minimum}..{maximum}")
    return value


def _number(value: object, context: str, minimum: float, maximum: float) -> float:
    if type(value) not in (int, float) or not math.isfinite(value) or not minimum <= value <= maximum:
        raise ValueError(f"{context} must be finite and in {minimum}..{maximum}")
    return float(value)


def _labels(value: object, context: str) -> dict[str, str]:
    raw = _table(value, context, required={"en", "ru"})
    for language in ("en", "ru"):
        label = raw[language]
        if type(label) is not str or not label.strip() or len(label) > 120:
            raise ValueError(f"{context}.{language} requires nonblank text of at most 120 characters")
    return {"en": raw["en"], "ru": raw["ru"]}


def _references(value: object, context: str, *, maximum: int) -> list[str]:
    if not isinstance(value, list) or not 1 <= len(value) <= maximum:
        raise ValueError(f"{context} must list 1..{maximum} identifiers")
    result = [_identifier(item, context) for item in value]
    if len(set(result)) != len(result):
        raise ValueError(f"{context} contains duplicate IDs")
    return result


def _selected(raw: dict, key: str, available: dict, *, maximum: int, profile: str) -> list[dict]:
    names = _references(raw.get(key), f"Interpretation profile '{profile}' {key}", maximum=maximum)
    missing = sorted(set(names) - available.keys())
    if missing:
        raise ValueError(f"Interpretation profile '{profile}' has unknown {key}: {', '.join(missing)}")
    selected = [available[name] for name in names]
    for name, value in zip(names, selected):
        if not isinstance(value, dict) or value.get("id") != name:
            raise ValueError(f"Interpretation {key} entry '{name}' must declare its matching id")
    return selected


def _dimension(raw: dict, definitions: set[str]) -> dict:
    _table(raw, "Dimension", required={"id", "labels", "sortOrder", "metricIds", "minimumCoverage", "minimumKnownMetrics"})
    identifier = _identifier(raw.get("id"), "Dimension id")
    context = f"Dimension '{identifier}'"
    _table(raw, context, required={"id", "labels", "sortOrder", "metricIds", "minimumCoverage", "minimumKnownMetrics"})
    metric_ids = _references(raw["metricIds"], f"{context} metricIds", maximum=64)
    for metric_id in metric_ids:
        _identifier(metric_id, f"{context} metricId", _METRIC_ID, 128)
    unknown = sorted(set(metric_ids) - definitions)
    if unknown:
        raise ValueError(f"{context} references metrics not generated by the selected metric profile: {', '.join(unknown)}")
    return {
        "id": identifier,
        "labels": _labels(raw["labels"], context),
        "sortOrder": _integer(raw["sortOrder"], f"{context} sortOrder", 0, 1_000_000),
        "metricIds": metric_ids,
        "minimumCoverage": _number(raw["minimumCoverage"], f"{context} minimumCoverage", 0, 100),
        "minimumKnownMetrics": _integer(raw["minimumKnownMetrics"], f"{context} minimumKnownMetrics", 1, len(metric_ids)),
    }


def _goals(raw: list[dict], defaults: list[MetricPreferenceDefault]) -> list[dict]:
    if not defaults:
        raise ValueError("Goal profiles require a nonempty dataset preference-default catalog")
    if len(defaults) > 128 or len({item.metric_id for item in defaults}) != len(defaults):
        raise ValueError("Dataset preference defaults must have 1..128 unique metric IDs")
    base = {
        default.metric_id: {
            "metricId": default.metric_id,
            "enabled": default.default_enabled,
            "direction": default.direction,
            "target": default.target_value,
            "limit": default.limit_value,
            "weight": default.weight,
        }
        for default in defaults
    }
    results = []
    for item in raw:
        _table(item, "Goal", required={"id", "labels", "sortOrder"}, optional=frozenset({"overrides"}))
        identifier = _identifier(item.get("id"), "Goal id")
        context = f"Goal '{identifier}'"
        _table(item, context, required={"id", "labels", "sortOrder"}, optional=frozenset({"overrides"}))
        overrides = item.get("overrides", [])
        if not isinstance(overrides, list) or len(overrides) > len(base):
            raise ValueError(f"{context} overrides exceed the preference-default catalog")
        entries = {metric_id: dict(values) for metric_id, values in base.items()}
        modified: set[str] = set()
        for change in overrides:
            if not isinstance(change, dict):
                raise ValueError(f"{context} overrides must be tables")
            metric_id = _identifier(change.get("metricId"), f"{context} metricId", _METRIC_ID, 128)
            _table(change, f"{context} override", required={"metricId"}, optional=frozenset({"enabled", "direction", "target", "limit", "weight"}))
            if metric_id not in entries:
                raise ValueError(f"{context} references metric '{metric_id}' absent from preference defaults")
            if metric_id in modified:
                raise ValueError(f"{context} has duplicate override for '{metric_id}'")
            if len(change) == 1:
                raise ValueError(f"{context} override for '{metric_id}' changes no values")
            modified.add(metric_id)
            entries[metric_id].update({key: value for key, value in change.items() if key != "metricId"})
        preferences = []
        for metric_id in base:
            pref = entries[metric_id]
            if type(pref["enabled"]) is not bool:
                raise ValueError(f"{context} '{metric_id}' enabled must be boolean")
            if pref["direction"] not in ("lower", "higher"):
                raise ValueError(f"{context} '{metric_id}' direction must be lower or higher")
            target = _number(pref["target"], f"{context} '{metric_id}' target", -1e12, 1e12)
            limit = _number(pref["limit"], f"{context} '{metric_id}' limit", -1e12, 1e12)
            _integer(pref["weight"], f"{context} '{metric_id}' weight", 1, 10)
            if ((pref["direction"] == "lower" and target >= limit)
                    or (pref["direction"] == "higher" and target <= limit)):
                raise ValueError(f"{context} '{metric_id}' direction conflicts with target/limit ordering")
            preferences.append({**pref, "target": target, "limit": limit})
        results.append({
            "id": identifier,
            "labels": _labels(item["labels"], context),
            "sortOrder": _integer(item["sortOrder"], f"{context} sortOrder", 0, 1_000_000),
            "preferences": preferences,
        })
    return results


def _rule(raw: dict, dimensions: dict[str, dict]) -> dict:
    required = {"id", "type", "dimensionIds", "templateKey", "minimumCoverage", "minimumKnownMetrics"}
    _table(raw, "Insight rule", required=required, optional=frozenset({"minimumScore", "maximumScore"}))
    identifier = _identifier(raw.get("id"), "Insight rule id")
    context = f"Insight rule '{identifier}'"
    _table(raw, context, required=required, optional=frozenset({"minimumScore", "maximumScore"}))
    operation = raw["type"]
    if type(operation) is not str or operation not in _RULE_TYPES:
        raise ValueError(f"{context} uses unsupported operation")
    count, *threshold_fields = _RULE_TYPES[operation]
    dimension_ids = _references(raw["dimensionIds"], f"{context} dimensionIds", maximum=2)
    if len(dimension_ids) != count:
        raise ValueError(f"{context} operation '{operation}' requires {count} dimension IDs")
    unknown = sorted(set(dimension_ids) - dimensions.keys())
    if unknown:
        raise ValueError(f"{context} references unknown dimensions: {', '.join(unknown)}")
    for field in ("minimumScore", "maximumScore"):
        if (field in raw) != (field in threshold_fields):
            raise ValueError(f"{context} operation '{operation}' requires only {threshold_fields}")
    known = _integer(raw["minimumKnownMetrics"], f"{context} minimumKnownMetrics", 1, 64)
    if any(known > len(dimensions[key]["metricIds"]) for key in dimension_ids):
        raise ValueError(f"{context} minimumKnownMetrics exceeds its dimension metric count")
    _identifier(raw["templateKey"], f"{context} templateKey", _TEMPLATE_KEY, 128)
    result = {
        "id": identifier,
        "type": operation,
        "dimensionIds": dimension_ids,
        "templateKey": raw["templateKey"],
        "minimumCoverage": _number(raw["minimumCoverage"], f"{context} minimumCoverage", 0, 100),
        "minimumKnownMetrics": known,
    }
    for field in threshold_fields:
        result[field] = _number(raw[field], f"{context} {field}", 0, 100)
    return result


def load_interpretation_catalog(
    config_path: Path | None,
    profile_name: str | None,
    metric_definitions: list[MetricDefinition],
    preference_defaults: list[MetricPreferenceDefault],
) -> dict | None:
    """Resolve a selected interpretation profile without GIS work or package I/O.

    A missing selection means legacy/no interpretation. Every selected reference must
    exist in the generated metric catalog; profile variations are always explicit.
    Goal overrides apply atomically over the complete dataset preference defaults.
    """
    if profile_name is None:
        return None
    if config_path is None:
        raise ValueError(f"Interpretation profile '{profile_name}' requires builder.interpretation_profiles")
    source = config_path.read_bytes()
    if len(source) > _MAX_CONFIG_BYTES:
        raise ValueError("Interpretation profile configuration is too large")
    payload = tomllib.loads(source.decode("utf-8"))
    _table(payload, "Interpretation configuration", required={"version", "profiles", "dimensions", "goals", "rules"})
    if type(payload["version"]) is not int or payload["version"] != 1:
        raise ValueError("Unsupported interpretation configuration version (expected 1)")
    for field in ("profiles", "dimensions", "goals", "rules"):
        if not isinstance(payload[field], dict):
            raise ValueError(f"Interpretation {field} must be a table")
    profile = payload["profiles"].get(profile_name)
    if profile is None:
        raise KeyError(f"Unknown interpretation profile '{profile_name}'")
    _table(profile, f"Interpretation profile '{profile_name}'", required={"dimension_ids", "goal_ids", "rule_ids"})
    if len({item.metric_id for item in metric_definitions}) != len(metric_definitions):
        raise ValueError("Generated metric definitions contain duplicate metric IDs")
    definitions = {item.metric_id for item in metric_definitions}
    dimension_items = _selected(profile, "dimension_ids", payload["dimensions"], maximum=32, profile=profile_name)
    goal_items = _selected(profile, "goal_ids", payload["goals"], maximum=16, profile=profile_name)
    rule_items = _selected(profile, "rule_ids", payload["rules"], maximum=64, profile=profile_name)
    dimensions = [_dimension(item, definitions) for item in dimension_items]
    if len({item["id"] for item in dimensions}) != len(dimensions):
        raise ValueError(f"Interpretation profile '{profile_name}' contains duplicate dimension IDs")
    goals = _goals(goal_items, preference_defaults)
    if len({item["id"] for item in goals}) != len(goals):
        raise ValueError(f"Interpretation profile '{profile_name}' contains duplicate goal IDs")
    dimension_map = {item["id"]: item for item in dimensions}
    rules = [_rule(item, dimension_map) for item in rule_items]
    if len({item["id"] for item in rules}) != len(rules):
        raise ValueError(f"Interpretation profile '{profile_name}' contains duplicate insight rule IDs")
    return {
        "version": 1,
        "dimensions": sorted(dimensions, key=lambda item: (item["sortOrder"], item["id"])),
        "goalProfiles": sorted(goals, key=lambda item: (item["sortOrder"], item["id"])),
        "insightRules": rules,
    }
